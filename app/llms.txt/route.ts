import { config, orderedMakes } from "@/lib/data";
import { SITE_URL, brandSlug, catalogEntries, entriesByMake } from "@/lib/catalog";

export const dynamic = "force-static";

export function GET() {
  const makes = orderedMakes();

  const lines: string[] = [
    `# GeeApp — Русификация, прошивка и установка приложений на штатные магнитолы авто`,
    ``,
    `> Официальный каталог услуг и цен GeeApp (${SITE_URL}). Программная адаптация штатных мультимедийных систем (ГУ) и приборных панелей китайских, корейских, японских и европейских автомобилей.`,
    ``,
    `## Форматы работы и география`,
    `- **Стационарный сервис в Челябинске:** ${config.address} (${config.hours}).`,
    `- **Региональная сеть (Екатеринбург, Москва, Санкт-Петербург, Казань, Уфа, Пермь, Новосибирск, Краснодар и др.):** работают проверенные мастера-партнёры, а также доступна дистанционная **онлайн-прошивка**.`,
    `- **Как распределяется заявка:** клиент оставляет заявку на сайте с указанием марки, модели, года и города; администратор проверяет версию штатного ГУ и направляет клиента к региональному мастеру-партнёру, на онлайн-прошивку или в сервис в Челябинске.`,
    `- **Телефон:** ${config.phone}`,
    ``,
    `## Ключевые услуги`,
    `1. **Установка пакета приложений и прошивка ГУ (от 8 000 до 30 000 ₽):** Яндекс Навигатор, Яндекс Музыка, VK Видео, Кинопоиск, RUTUBE, ТВ, радио, RuStore, разделение экрана (Split Screen), привязка кнопок мультируля, вывод навигации на проекцию (HUD) и приборную панель.`,
    `2. **Русификация мультимедиа и приборной панели (цена по запросу / в составе комплекса):** полный программный перевод меню, настроек авто, климата и ассистентов.`,
    `3. **Безопасность для гарантии:** работа выполняется программно поверх штатной системы без пайки проводки, с возможностью быстрого возврата к заводскому состоянию перед визитом к дилеру.`,
    ``,
    `## Важные технические ограничения`,
    `- **Geely Monjaro Rest 2025:** комплекс (русификация + приложения, 30 000 ₽) поддерживается для авто выпуска **до марта 2025 года**.`,
    `- **Haval Jolion:** базовая установка приложений — 8 000 ₽; активация звукового процессора DTS — +1 000 ₽.`,
    `- **Geely Coolray / Atlas Pro / Belgee X50 (1 серия):** пакет через разблокировку Android Auto (и CarPlay с адаптером Carlinkit) — 10 000 ₽.`,
    `- **Haval M6:** НЕ прошивается (штатное ГУ на урезанном Linux без Android).`,
    ``,
    `## Каталог поддерживаемых марок и моделей (${catalogEntries.length} позиций)`,
  ];

  for (const make of makes) {
    lines.push(``, `### ${make} (${SITE_URL}/brand/${brandSlug(make)})`);
    for (const entry of entriesByMake(make)) {
      const services: string[] = [];
      if (!entry.supported) {
        services.push("Не прошивается (закрытый Linux)");
      } else {
        if (entry.car?.service === "apps") services.push(`Приложения/прошивка: ${entry.priceDisplay}`);
        if (entry.rus) services.push("Русификация: по запросу");
        if (entry.car?.service === "inquiry") services.push("Подбор по фото ГУ: по запросу");
      }
      const note = entry.compatibilityNote ? ` — ${entry.compatibilityNote}` : "";
      lines.push(
        `- [${entry.fullTitle}](${SITE_URL}/model/${entry.slug}): ${services.join(", ")}${note}`
      );
    }
  }

  return new Response(lines.join("\n") + "\n", {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Cache-Control": "public, max-age=3600, s-maxage=86400",
    },
  });
}